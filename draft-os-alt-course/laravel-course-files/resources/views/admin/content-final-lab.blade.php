                <h2>Легенда</h2>
                <p>Тебе передан новый сервер на ОС ALT Linux. Система только что установлена. Твоя задача — настроить его согласно корпоративным требованиям безопасности перед вводом в эксплуатацию.</p>

                <h3>Задание 1. Инвентаризация системы</h3>
                <p>Тебе передали новый сервер. Прежде чем приступать к настройке — нужно разобраться что за система перед тобой. Это стандартная процедура при приёмке любого сервера: зафиксировать базовые сведения о системе чтобы понимать с чем работаешь и иметь отправную точку для дальнейшей настройки.</p>
                <p>Собери следующие сведения и запиши их в файл <code>/root/exam-report.txt</code>:</p>
                <ul>
                    <li>Название и версия ОС</li>
                    <li>Версия ядра и архитектура процессора</li>
                    <li>Режим загрузки по умолчанию — серверный или графический</li>
                    <li>Подключённые репозитории</li>
                </ul>

                <h3>Задание 2. Административный веб-интерфейс</h3>
                <p>Тебе передали сервер на ОС Альт. Предыдущий администратор установил систему и даже поставил нужные пакеты, но до настройки не дошёл — веб-интерфейс управления сервером недоступен. Служба эксплуатации требует чтобы администраторы могли управлять сервером удалённо через браузер без подключения по SSH.</p>
                <p>Обеспечь работу веб-интерфейса ЦУС и добавь его в автозагрузку — интерфейс должен подниматься автоматически при каждом старте сервера.</p>
                <p>После настройки веб-интерфейс должен быть доступен по адресу <code>https://&lt;IP-сервера&gt;:8080</code>.</p>

                <h3>Задание 3. Политика паролей</h3>
                <p>Компания проводит аудит безопасности. Аудитор выявил два нарушения корпоративного стандарта на сервере:</p>
                <ul>
                    <li>Система принимает пароли, состоящие только из одного класса символов — например только цифры или только строчные буквы. Это прямое нарушение парольной политики.</li>
                    <li>Ограничения на сложность пароля не распространяются на суперпользователя — root может установить любой пароль в обход политики.</li>
                </ul>
                <p>Устранить оба нарушения. После исправления система не должна принимать пароли из одного класса символов ни от одного пользователя, включая root.</p>
                <p><strong>Справочная информация:</strong> политика паролей в Альт Линукс настраивается в файле <code>/etc/passwdqc.conf</code>. Параметр <code>min</code> задаёт минимальную длину пароля в зависимости от количества классов символов — пять значений через запятую. Параметр <code>enforce</code> определяет, на кого распространяется политика.</p>
                <pre class="check-log-pre">cat /etc/passwdqc.conf</pre>

                <h3>Задание 4. Контроль целостности</h3>
                <p>Служба безопасности сообщила о подозрительной активности на сервере. Есть основания полагать, что один или несколько системных файлов были модифицированы. Проверить целостность установленных пакетов, найти изменённые файлы, определить, каким пакетам они принадлежат, и восстановить исходное состояние. После восстановления повторная проверка не должна выявлять расхождений с эталоном.</p>
                <p><strong>Справочная информация:</strong> RPM хранит эталонные метаданные всех установленных файлов. Команда проверки сравнивает текущее состояние с эталоном и выводит только изменённые файлы. Каждая строка содержит флаги и путь:</p>
                <pre class="check-log-pre">S.5....T.  /usr/bin/somefile   ← изменился хэш и размер
.M.......  /bin/otherfile      ← изменились права доступа</pre>
                <p>Чтобы узнать, какому пакету принадлежит файл:</p>
                <pre class="check-log-pre">rpm -qf /путь/к/файлу</pre>
                <p>Для восстановления файлов пакета:</p>
                <pre class="check-log-pre">apt-get install --reinstall &lt;имя_пакета&gt;</pre>

                <h3>Задание 5. Делегирование прав через Polkit</h3>
                <p>В компании есть группа сетевых администраторов. По корпоративному регламенту они должны иметь возможность управлять системными службами через systemd не зная пароля root.</p>
                <ul>
                    <li>Группа называется <code>netops</code></li>
                    <li>Пользователь <code>student</code> должен входить в эту группу</li>
                    <li>Члены группы <code>netops</code> должны иметь право на действие <code>org.freedesktop.systemd1.manage-units</code> без запроса пароля</li>
                    <li>Правило должно быть оформлено через механизм Polkit и сохраняться после перезапуска службы</li>
                </ul>
                <p><strong>Справочная информация:</strong></p>
                <p>Правила Polkit хранятся в <code>/etc/polkit-1/rules.d/</code> в виде файлов с расширением <code>.rules</code>. Файлы применяются в алфавитном порядке по имени.</p>
                <p>Каждое правило — это JavaScript-функция вида:</p>
                <pre>polkit.addRule(function(action, subject) {
    if (/* условие на действие */ &&
        /* условие на пользователя */) {
        return polkit.Result.YES;  // разрешить
    }
    // если условия не совпали — передать следующему правилу
});</pre>
                <p>Что можно проверять в условиях:</p>
                <ul>
                    <li><code>action.id</code> — идентификатор действия (строка)</li>
                    <li><code>subject.isInGroup("название")</code> — входит ли пользователь в группу</li>
                    <li><code>subject.user</code> — имя пользователя</li>
                    <li><code>subject.local</code> — локальная сессия или нет</li>
                </ul>
                <p>После создания файла правил необходимо перезапустить службу Polkit чтобы изменения вступили в силу.</p>
                <p>Проверить что правило загружено можно командой:</p>
                <pre>journalctl -u polkit --since "1 minute ago"</pre>

                <h3>Задание 6. Ограничение доступа к sudo</h3>
                <p>Политика безопасности компании требует чтобы выполнение команд с правами суперпользователя через <code>sudo</code> было доступно только системным администраторам входящим в специальную группу. Рядовые сотрудники не должны иметь возможности использовать <code>sudo</code> даже если они указаны в <code>/etc/sudoers</code>.</p>
                <p>Текущее состояние: механизм ограничения sudo по группе отключён — любой пользователь у которого есть запись в sudoers может выполнять команды от root.</p>
                <p>Включи механизм при котором <code>sudo</code> доступен только членам группы <code>wheel</code>. Используй для этого инструмент управления доступом к системным утилитам уникальный для Альт Линукс.</p>

