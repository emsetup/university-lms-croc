<p class="course-audience-intro__lead">
    Изначально этот материал планировался как <strong>лабораторная работа и практикум</strong>, а не как первое знакомство с операционной системой.
    Мы исходим из того, что вы <strong>уже владеете администрированием типичного корпоративного Linux</strong>&nbsp;— на уровне, который можно сопоставить с подготовкой к сертификации
    <abbr title="Red Hat Certified System Administrator">RHCSA</abbr>: командная строка, пользователи и права, службы и автозапуск, сеть и файрвол, хранилища, журналы и базовая диагностика.
</p>
<p>
    <strong>Задача трека другая:</strong> относительно быстро и по делу разобраться с <strong>ОС «Альт»</strong> как с отечественным дистрибутивом&nbsp;— менеджером пакетов и репозиториями, особенностями инструментов и политик обновлений, типичными отличиями от привычных Enterprise Linux.
    Повторять общие азы мы не ставим целью: фокус на том, что отличает или специфично для «Альт» в реальной работе.
</p>
<p class="muted course-modal__note">
    Если ваш опыт с Linux пока небольшой, содержание может оказаться слишком насыщенным&nbsp;— это нормально: имеет смысл сначала пройти вводный курс по Linux, а затем вернуться к этому треку, чтобы получить от него максимум пользы.
</p>
